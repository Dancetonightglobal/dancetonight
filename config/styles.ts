// The style taxonomy (SPEC section 3, PLAN section 4): families, styles, listing types,
// multilingual synonyms for matching, and the query phrases the discovery agent searches for.
// This is code, versioned with the app; `events.styles[]` stores the style keys below.
// Family keys match the DESIGN.md section 3 stock tokens (`bg-stock-salsa`, ...) and the
// hex values live here so the palette and the taxonomy cannot drift apart.
//
// Matching rules (matchStyles):
// 1. Text and phrases are normalized the same way: NFKD, Latin diacritics stripped, lowercased,
//    every run of non-letter/non-digit characters collapsed to one space. So "práctica" ==
//    "practica", "K-pop" == "k pop", "rock'n'roll" == "rock n roll".
// 2. Latin-script phrases match on whole tokens only ("kiz" never matches "kizomba"); phrases in
//    Japanese, Korean, Chinese or Arabic script match as substrings because those scripts have no word spaces
//    (Arabic attaches ال/و/ب/ل to the word, D-1062).
// 3. Every candidate match is collected, then the longest match wins (more characters first,
//    earlier position on ties) and overlapping shorter matches are dropped. "silent disco" beats
//    "disco night"; "modern jive" beats "jive".
// 4. FALSE_FRIENDS are phrases that use a dance word in another sense ("salsa verde",
//    "breaking news"). They take part in the same longest-match pass and map to nothing, so the
//    dance word inside them cannot match on its own.
// 5. Bare words that mostly mean something else (house, rock, swing, blues, disco, garage,
//    ballroom, country, folk, casino, contra, ...) are never synonyms by themselves; only
//    compounds with a dance context word are ("house dance", "soirée rock", "swing night",
//    "ballroom dancing"). Dance words that are dance words in most contexts but have one
//    well-known other sense (salsa the sauce, merengue the meringue) stay synonyms and their
//    other-sense phrases go in FALSE_FRIENDS.
// 6. A phrase may map to more than one style or family only through AMBIGUOUS_SYNONYMS
//    ("sbk" is salsa, bachata and kizomba; "jive" is the swing jive and the ballroom jive).
// 7. WEAK_SYNONYMS are generic event words ("social dancing", "Tanzabend", "DJ set",
//    "dance party") that only count when nothing stronger matched, so "salsa social with DJ"
//    is salsa, not salsa plus a club night, while "DJ night at the Loft" is a club night.
// 8. `langs` narrows the synonyms used to those languages plus English, which is always on
//    because listings everywhere mix English and the dance's own vocabulary. Without `langs`
//    every language is used.


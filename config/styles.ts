/**
 * Label for any taxonomy key. "salsa" and "kizomba" are both a style and a family; the style
 * wins here because `events.styles[]` stores style keys. Use familyLabel() for the family.
 */
export function labelFor(key: StyleKey | FamilyKey | ListingType): string {
  if (isStyleKey(key)) return styleLabel(key);
  if (isFamilyKey(key)) return familyLabel(key);
  return listingTypeLabel(key);
}

/**
 * Query phrases the discovery agent combines with the metro name: the language's phrases
 * first, then the English ones, because listings everywhere also use English dance words.
 * A language without its own list falls back to English alone.
 */
export function searchQueriesFor(familyKey: FamilyKey, lang: Lang = "en"): readonly string[] {
  const family = familyByKey.get(familyKey);
  if (!family) throw new Error(`Unknown family key: ${familyKey}`);
  const queries: Synonyms = family.queries;
  const local = lang === "en" ? [] : (queries[lang] ?? []);
  return unique([...local, ...queries.en]);
}

// Matching

const LATIN_DIACRITICS = /[̀-ͯ]/g;
// Devanagari vowel signs are marks; keep them so Hindi and Marathi words stay whole (D-620).
const NON_WORD = /[^\p{L}\p{N}\p{Script=Devanagari}\p{Script=Gurmukhi}]+/gu;
// Scripts that have no word spaces: Chinese, Japanese, Korean, Arabic (Arabic attaches ال/و/ب/ل, D-1062)
const SUBSTRING_SCRIPTS =
  /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}\p{Script=Arabic}]/u;
const LIGATURES: Record<string, string> = { ß: "ss", ø: "o", œ: "oe", æ: "ae", ł: "l", đ: "d" };

/** Accent-, case- and punctuation-insensitive form used on both sides of a match (rule 1). */
export function normalizeForMatch(input: string): string {
  return (
    input
      .normalize("NFKD")
      .replace(LATIN_DIACRITICS, "")
      .toLowerCase()
      .replace(/ı/g, "i") // D-682: dotless ı folds to i for Turkish matching
      // D-1062: remove Arabic marks (tashkeel, combining hamza/madda, Quranic marks). NFKD has already split
      // أ/إ/آ into ا plus a combining hamza or madda, so removing the mark folds every alef variant to ا on both sides.
      .replace(/[ً-ٰٟۖ-ۭ]/g, "")
      // D-1062: remove tatweel
      .replace(/ـ/g, "")
      // D-1062: fold alef maqsura (ى) to ya (ي) and ta marbuta (ة) to ha (ه)
      .replace(/ى/g, "ي")
      .replace(/ة/g, "ه")
      .replace(/[ßøœæłđ]/g, (c) => LIGATURES[c] ?? c)
      .replace(NON_WORD, " ")
      .trim()
  );
}

type Strength = "strong" | "weak" | "none";

interface IndexEntry {
  readonly needle: string;
  readonly tokens: readonly string[];
  readonly lang: Lang | null;
  readonly strength: Strength;
  readonly styles: readonly StyleKey[];
  readonly families: readonly FamilyKey[];
}

interface MatchIndex {
  readonly byFirstToken: ReadonlyMap<string, readonly IndexEntry[]>;
  readonly cjk: readonly IndexEntry[];
}

let matchIndex: MatchIndex | null = null;

function buildIndex(): MatchIndex {
  const entries: IndexEntry[] = [];
  const add = (
    phrase: string,
    lang: Lang | null,
    strength: Strength,
    styles: readonly StyleKey[],
    families: readonly FamilyKey[],
  ) => {
    const needle = normalizeForMatch(phrase);
    if (!needle) return;
    entries.push({ needle, tokens: needle.split(" "), lang, strength, styles, families });
  };
  for (const style of STYLES) {
    const synonyms: Synonyms = style.synonyms;
    for (const lang of LANGS) {
      for (const phrase of synonyms[lang] ?? []) add(phrase, lang, "strong", [style.key], []);
    }
  }
  for (const family of FAMILIES) {
    const synonyms: Synonyms = family.synonyms;
    for (const lang of LANGS) {
      for (const phrase of synonyms[lang] ?? []) add(phrase, lang, "strong", [], [family.key]);
    }
  }
  const ambiguous: readonly PhraseEntry[] = AMBIGUOUS_SYNONYMS;
  const weak: readonly PhraseEntry[] = WEAK_SYNONYMS;
  for (const e of ambiguous) add(e.phrase, e.lang, "strong", e.styles ?? [], e.families ?? []);
  for (const e of weak) add(e.phrase, e.lang, "weak", e.styles ?? [], e.families ?? []);
  for (const phrase of FALSE_FRIENDS) add(phrase, null, "none", [], []);

  const byFirstToken = new Map<string, IndexEntry[]>();
  const substringScripts: IndexEntry[] = [];
  for (const entry of entries) {
    if (SUBSTRING_SCRIPTS.test(entry.needle)) {
      substringScripts.push(entry);
      continue;
    }
    const first = entry.tokens[0];
    if (first === undefined) continue;
    const list = byFirstToken.get(first) ?? [];
    list.push(entry);
    byFirstToken.set(first, list);
  }
  return { byFirstToken, cjk: substringScripts };
}

interface Span {
  readonly start: number;
  readonly end: number;
  readonly entry: IndexEntry;
}

export interface StyleMatch {
  /** Style keys in order of first appearance in the text. */
  styles: StyleKey[];
  /** Families of the matched styles plus family-level matches, in order of first appearance. */
  families: FamilyKey[];
}

/**
 * Find the styles and families a piece of text (title, description, page) talks about.
 * `langs` narrows synonyms to those languages plus English; omit it to use every language.
 */
export function matchStyles(text: string, langs?: readonly string[]): StyleMatch {
  matchIndex ??= buildIndex();
  const allowed = langs ? new Set<string>([...langs, "en"]) : null;
  const langOk = (entry: IndexEntry) =>
    entry.lang === null || allowed === null || allowed.has(entry.lang);

  const norm = normalizeForMatch(text);
  if (!norm) return { styles: [], families: [] };

  // Token positions as character offsets into the normalized string.
  const tokens: { text: string; start: number }[] = [];
  for (const m of norm.matchAll(/[^ ]+/g)) tokens.push({ text: m[0], start: m.index });

  const candidates: Span[] = [];
  for (let i = 0; i < tokens.length; i++) {
    const head = tokens[i];
    if (!head) continue;
    for (const entry of matchIndex.byFirstToken.get(head.text) ?? []) {
      if (!langOk(entry)) continue;
      let ok = true;
      for (let k = 1; k < entry.tokens.length; k++) {
        if (tokens[i + k]?.text !== entry.tokens[k]) {
          ok = false;
          break;
        }
      }
      if (!ok) continue;
      const last = tokens[i + entry.tokens.length - 1];
      if (!last) continue;
      candidates.push({ start: head.start, end: last.start + last.text.length, entry });
    }
    // D-882: a German compound's dance head ("walzerfruhstuck" names walzer), strong one-word synonyms only.
    const compound = matchIndex.byFirstToken.has(head.text) ? null : compoundHead(head.text);
    for (const entry of compound === null ? [] : (matchIndex.byFirstToken.get(compound) ?? [])) {
      if (entry.tokens.length !== 1 || entry.strength !== "strong" || !langOk(entry)) continue;
      candidates.push({ start: head.start, end: head.start + head.text.length, entry });
    }
  }
  for (const entry of matchIndex.cjk) {
    if (!langOk(entry)) continue;
    let from = 0;
    for (;;) {
      const at = norm.indexOf(entry.needle, from);
      if (at < 0) break;
      candidates.push({ start: at, end: at + entry.needle.length, entry });
      from = at + 1;
    }
  }

  // Longest match wins; ties go to the earlier position (rule 3).
  candidates.sort((a, b) => b.end - b.start - (a.end - a.start) || a.start - b.start);
  const chosen: Span[] = [];
  for (const c of candidates) {
    if (chosen.some((s) => c.start < s.end && s.start < c.end)) continue;
    chosen.push(c);
  }
  chosen.sort((a, b) => a.start - b.start);

  const hasStrong = chosen.some(
    (s) =>
      s.entry.strength === "strong" && (s.entry.styles.length > 0 || s.entry.families.length > 0),
  );
  const styles: StyleKey[] = [];
  const families: FamilyKey[] = [];
  for (const { entry } of chosen) {
    if (entry.strength === "none") continue;
    if (entry.strength === "weak" && hasStrong) continue;
    for (const s of entry.styles) {
      if (!styles.includes(s)) styles.push(s);
      const f = familyOf(s);
      if (!families.includes(f)) families.push(f);
    }
    for (const f of entry.families) if (!families.includes(f)) families.push(f);
  }
  return { styles, families };
}

function unique<T>(items: readonly T[]): T[] {
  return [...new Set(items)];
}

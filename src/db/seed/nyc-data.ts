export interface VenueDef {
  slug: string;
  name: string;
  lat: number;
  lng: number;
  line1: string;
  locality: string;
  region: "NY" | "NJ";
  postcode: string;
  neighborhood: string;
  kind: VenueKind;
  danceFloor: "yes" | "no" | "unknown";
  websiteUrl: string | null;
  /** Opening hours; with `openNight` these produce venue_open_night rows. */
  hours?: VenueHours;
  /** What an open night at this venue is like, for the generated listing. */
  openNight?: {
    styles: StyleKey[];
    prices: Price[];
    isFree: boolean | null;
    ageMin: number | null;
    summary: string;
    source: string;
    /** Marked cancelled for tonight ("closed tonight for a private event"). */
    cancelledTonight?: boolean;
  };
}


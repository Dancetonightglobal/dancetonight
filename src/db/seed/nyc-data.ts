// Listings: what every series and one-off shares

export interface ListingFacts {
  title: string;
  listingType: ListingType;
  styles: StyleKey[];
  organizer: string | null;
  /**
   * The venue's slug, or null for a listing whose source names no place we can put on the map: it
   * is shown as "Location not listed", with no pin (D-082). One-offs only; a series has a venue.
   */
  venue: string | null;
  /** Minutes the lesson starts before (negative) or after the main start; null when no lesson. */
  lessonOffsetMin?: number | null;
  /** Minutes doors open before the main start (negative); null when not listed. */
  doorsOffsetMin?: number | null;
  /** Length of the night in minutes; null when the end is not listed. */
  durationMin: number | null;
  prices: Price[];
  isFree: boolean | null;
  /**
   * A page that sells this night: one event's page, never a site's home page, a list of its
   * nights or a ticket seller's organiser page (D-073, src/domain/event-links.ts).
   */
  ticketUrl?: string | null;
  /**
   * Each source's own page for this one event, by source slug (event_sources.event_url, D-073).
   * A source left out only lists the night among others, and the card says "Listed on" it.
   */
  eventUrls?: Record<string, string>;
  level?: string | null;
  partnerRequired?: boolean | null;
  ageMin?: number | null;
  dressCode?: string | null;
  floor?: string | null;
  indoorOutdoor?: "indoor" | "outdoor" | "both" | null;
  /** `liveMusic`: true for a live band, musicians or an orchestra; false for DJs; null when the listing does not say. */
  music?: {
    djs: string[];
    bands: string[];
    genreMix: string | null;
    liveMusic: boolean | null;
  } | null;
  crowdSizeHint?: string | null;
  summary: string;
  /** Primary source slug, then secondaries. */
  sources: string[];
  /** 0 to 1; how much we trust the facts. */
  confidence: number;
  /** Our own short note per field, standing in for the harvester's evidence snippet. */
  evidence?: Record<string, string>;
}

export type SeriesRule =
  | { kind: "weekly"; weekday: Weekday; time: string; interval?: number }
  | { kind: "monthly"; weekday: Weekday; ordinal: 1 | 2 | 3 | 4 | -1; time: string }
  | {
      /** A weekly rule limited to some months, e.g. a summer series (absent the rest of the year). */
      kind: "seasonal";
      weekdays: Weekday[];
      time: string;
      months: number[];
      /** DTSTART calendar date inside the season, "YYYY-MM-DD". */
      dtstartDate: string;
    };

export interface SeriesDef extends ListingFacts {
  slug: string;
  venue: string;
  rule: SeriesRule;
  /** True when the primary source is first-party and re-checked day-of: tonight's row is confirmed_today. */
  confirmsDaily: boolean;
  /** Two sources disagree on the end: each source's own end, minutes after the start, by source slug. */
  conflictingEnd?: Record<string, number>;
}

interface OneOffBase extends ListingFacts {
  slug: string;
  /** Calendar nights from tonight's night date; 0 is tonight. */
  daysFromNow: number;
  /**
   * "cancelled" keeps the night on the bill, marked "Cancelled tonight", the way a venue's
   * `cancelledTonight` does for an open night; use it on a night with daysFromNow 0 only.
   */
  confirmation: "confirmed_today" | "recurring_unconfirmed" | "cancelled";
}

/** A one-off whose source lists a start: its end, when listed, is the start plus durationMin. */
interface TimedOneOff extends OneOffBase {
  /** "HH:MM" local; a time before 06:00 lands in the small hours of that night. */
  time: string;
  endTime?: never;
}

/**
 * A one-off whose source gives its night and no time (D-060): doors, lesson and dancing are all
 * null, the night is `daysFromNow` itself, and nothing is derived from an assumed start.
 */
interface UntimedOneOff extends OneOffBase {
  /** null: the source lists the night and no start time, shown as "Time not listed". */
  time: null;
  /** Always null: there is no start to measure a length from. */
  durationMin: null;
  /**
   * "HH:MM" local when the source lists an end on its own ("until 2am"), else null. A time before
   * 06:00 lands in the small hours of that night.
   */
  endTime: string | null;
}

/** `time` is "HH:MM" local, or null for a listing with a date and no time (D-060). */
export type OneOffDef = TimedOneOff | UntimedOneOff;


// "now": series are rules, one-offs are day offsets, venue open nights come from hours. The
// builder in nyc.ts turns it into insert-shaped rows for a given instant.
//
// Venues, organizers and weekly nights are the real ones from SOURCES.md section 8 (snippet-only
// research, so times, prices and a few addresses are best-effort placeholders for mock mode and
// carry low confidence; Phase 2 harvests the truth). Club venues from the "not yet researched"
// list appear with illustrative hours so that venue_open_night rows exist. Nothing here is
// rendered as a source's own words: evidence strings are our own short notes.

